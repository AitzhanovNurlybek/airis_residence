/**
 * Как добраться из аэропорта.
 *
 * Просьба заказчицы: туристы заходят на сайт на любом языке, и многие —
 * особенно европейцы — хотят ехать из аэропорта автобусом, а не такси.
 *
 * Маршруты взяты из 2ГИС, построенных именно до адреса отеля (2026-09-29).
 * Публичные источники чаще советуют автобус 92 — он действительно главный
 * из аэропорта, но в сторону города проходит не мимо отеля, и 2ГИС до этого
 * адреса его не предлагает. Выдавать туристу «популярный» маршрут вместо
 * подходящего — значит оставить его с чемоданом в двух кварталах от цели.
 *
 * Время и интервалы здесь — ориентир, а не расписание: оно меняется, и
 * точное время гость видит по кнопкам маршрута ниже блока. Поэтому числа
 * округлены («около 1,5 часа»), а не переписаны до минуты.
 *
 * Отсюда же данные берёт консьерж в WhatsApp — через /api/knowledge.
 */
