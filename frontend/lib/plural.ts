/**
 * Склонение существительных при числах.
 *
 * Появилось не от любви к грамматике: на главной висело «34 номеров» — в
 * заголовке, в первом экране и в описании для поисковиков. Число подставлялось
 * в текст как есть, и ошибку видел каждый посетитель. Ровно та мелочь, по
 * которой судят обо всей работе.
 *
 * Хардкодить правильную форму нельзя: номеров у отеля станет 35 или 40, и
 * вписанное сегодня руками станет неверным завтра.
 */

/**
 * Выбрать форму слова по числу.
 *
 * Порядок форм — как в русской грамматике: для 1, для 2–4, для 5–20.
 *
 * ```ts
 * plural(34, "номер", "номера", "номеров") // "номера"
 * ```
 */
export function plural(count: number, one: string, few: string, many: string): string {
  const n = Math.abs(count) % 100;
  // Одиннадцать–четырнадцать выпадают из общего правила: у них всегда
  // последняя форма, хотя оканчиваются они на 1, 2, 3 и 4.
  if (n >= 11 && n <= 14) return many;
  const last = n % 10;
  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;
  return many;
}

/** «34 номера», «1 номер», «11 номеров». */
export function rooms(count: number): string {
  return plural(count, "номер", "номера", "номеров");
}

/** «5 типов», «2 типа», «1 тип». */
export function types(count: number): string {
  return plural(count, "тип", "типа", "типов");
}
