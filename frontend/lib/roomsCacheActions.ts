"use server";

import { updateTag } from "next/cache";

import { CONTENT_TAG } from "@/lib/rooms";

/**
 * Сброс кэша номеров после правки в админке.
 *
 * Почему серверное действие, а не обработчик маршрута: нужен именно
 * `updateTag` — он гасит запись и заставляет следующий запрос дождаться
 * свежих данных. Родственный `revalidateTag` в Next 16 помечает запись
 * устаревшей и отдаёт её ещё раз, пока обновляет в фоне, — то есть
 * ровно то, из-за чего кэш здесь когда-то и выключили: сотрудник
 * сохранял цену и видел на сайте старую. А `updateTag` доступен только
 * в серверных действиях.
 */
export async function refreshRoomsCache(): Promise<void> {
  updateTag(CONTENT_TAG);
}
