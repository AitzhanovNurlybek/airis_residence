"""
Придумать пароль и записать его, чтобы не потерять.

Пароли в этом проекте нужны регулярно: админка сайта, ответственные
корпоративных клиентов, доступы к чужим кабинетам. Придумывать их головой
плохо — получается «Airis2026», который потом утекает в переписку и живёт
там годами.

    ./.venv/Scripts/python.exe parol.py
    ./.venv/Scripts/python.exe parol.py "админка сайта"

Без имени — просто печатает пароль. С именем — ещё и дописывает его в
`backend/paroli.txt` с датой, чтобы через месяц было понятно, что это за
строка и откуда.

────────────────────────────────────────────────────────────────────────
ПОЧЕМУ ИМЕННО ТАК

**Файл лежит вне git.** Он добавлен в `.gitignore` отдельной строкой, а не
случайно подходит под чужой шаблон: пароли не должны зависеть от совпадения.

**Пароль не собирается из слов.** Никаких «Airis» и «2026»: имя отеля и год
— первое, что перебирают. Берутся случайные символы из набора, где нет
похожих друг на друга (`0` и `O`, `1` и `l`), — их путают, когда диктуют по
телефону.

**Случайность настоящая.** `secrets`, а не `random`: второй предсказуем по
предыдущим значениям и для паролей не годится.

────────────────────────────────────────────────────────────────────────
ГДЕ ЭТОМУ ФАЙЛУ НЕ МЕСТО

Это записная книжка, а не хранилище. Она удобна, пока пароль нужно куда-то
вписать сегодня. Всё, что живёт дольше недели, переносите в менеджер
паролей: файл на рабочем столе не переживёт ни переустановку системы, ни
чужой взгляд через плечо.
"""

from __future__ import annotations

import io
import secrets
import sys
from datetime import datetime
from pathlib import Path

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")

#: Куда записываем. Рядом с .env, в той же папке и с тем же уровнем доверия.
FILE = Path(__file__).parent / "paroli.txt"

#: Из чего собираем пароль.
#:
#: Исключены символы, которые путают при диктовке и переписывании: ноль и
#: буква O, единица с латинской l и I. Пароль отеля рано или поздно диктуют
#: по телефону администратору — и «ноль или о?» стоит дороже, чем два
#: лишних символа длины.
ALPHABET = "abcdefghijkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789"

#: Длина. Двадцать символов из этого набора — заведомо больше, чем нужно,
#: и по-прежнему можно продиктовать.
LENGTH = 20


def make(length: int = LENGTH) -> str:
    """Случайный пароль. secrets, а не random: random для паролей не годится."""
    return "".join(secrets.choice(ALPHABET) for _ in range(length))


def remember(password: str, label: str) -> Path:
    """Дописать пароль в файл с пометкой и датой."""
    when = datetime.now().strftime("%Y-%m-%d %H:%M")
    line = f"{when}  {label}\n            {password}\n\n"

    if not FILE.exists():
        FILE.write_text(
            "# Пароли проекта. Файл вне git — наружу не уходит.\n"
            "# Это записная книжка, а не хранилище: то, что нужно надолго,\n"
            "# переносите в менеджер паролей.\n\n",
            encoding="utf-8",
        )
    with FILE.open("a", encoding="utf-8") as handle:
        handle.write(line)
    return FILE


def main() -> int:
    label = " ".join(sys.argv[1:]).strip()
    password = make()

    print(f"\n  {password}\n")
    if not label:
        print("  Чтобы ещё и записать, добавьте название:")
        print('      ./.venv/Scripts/python.exe parol.py "админка сайта"')
        return 0

    path = remember(password, label)
    print(f"  записан в {path.name} как «{label}»")
    print("  файл вне git — наружу не уйдёт")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
