"""
Точка входа для площадок, которые сами запускают приложение.

Vercel и большинство PaaS ищут переменную `app` в файле `main.py`
или `index.py` в корне сервиса. Настоящий код живёт в пакете `app/`,
здесь только пере-экспорт, чтобы не плодить копию.

Локально по-прежнему работает и привычное:
    uvicorn app.main:app --reload

────────────────────────────────────────────────────────────────────────
ПОЧЕМУ ИМПОРТ ОБЁРНУТ

Если импорт приложения падает, площадка отвечает своим общим «функция не
выполнилась» и не говорит ничем, что именно сломалось. Причина видна
только в журнале площадки, а доступа к нему может не быть — и тогда сбой
чинится вслепую, перебором.

Так и вышло: сайт лежал часами, наружу шло FUNCTION_INVOCATION_FAILED без
единой подробности. Поэтому здесь стоит заглушка: она отвечает тем самым
разбором ошибки, который иначе остался бы в чужом журнале.

Заглушка написана без единой зависимости — на голом ASGI. Импорт мог
сломаться как раз на fastapi, и тогда попытка ответить через него
провалилась бы следом.
"""

from __future__ import annotations

try:
    from app.main import app
except Exception:  # noqa: BLE001 — здесь важно поймать вообще всё
    import traceback

    _РАЗБОР = traceback.format_exc()

    async def app(scope, receive, send) -> None:  # type: ignore[misc]
        """Приложение не поднялось. Отвечаем причиной, а не молчанием."""
        if scope["type"] != "http":
            return
        тело = (
            "Приложение не запустилось.\n\n"
            + _РАЗБОР
        ).encode("utf-8")
        await send({
            "type": "http.response.start",
            "status": 500,
            "headers": [(b"content-type", b"text/plain; charset=utf-8")],
        })
        await send({"type": "http.response.body", "body": тело})


__all__ = ["app"]
