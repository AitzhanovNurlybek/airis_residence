def language_of(text: str) -> str:
    """Язык одной реплики: kk, ru, en — или пусто, если букв в ней нет.

    Грубо, но надёжно для того, что важно: нет ни одной русской буквы — значит
    не по-русски, и отвечать по-русски нельзя. Латиница любого языка даёт en:
    отвечать гостю будет модель, а ей хватает пометки «не по-русски».
    """
    текст = text or ""
    if any(ch in KAZAKH_LETTERS for ch in текст):
        return "kk"
    буквы = [ch for ch in текст if ch.isalpha()]
    if not буквы:
        return ""
    if any("а" <= ch.lower() <= "я" or ch.lower() == "ё" for ch in буквы):
        return "ru"
    return "en"


def guest_language(text: str = "", phone: str = "", earlier: Iterable[str] = ()) -> str:
    """На каком языке писать гостю: ru, en или kk.

    По порядку:
    1. По его сообщению — если в нём есть буквы.
    2. По прошлым репликам гостя (`earlier`, от свежих к старым), если в
       сообщении букв нет: номер брони, дата, смайл, файл. 2026-10-05 номер
       брони одними цифрами получил ответ без пометки о языке.
    3. По номеру: +7 — по-русски, остальные — по-английски.

    Короткая латиница — до трёх слов — язык разговора не меняет: «ok»,
    «Comfort Plus» от гостя, который писал по-русски, — всё ещё русский
    разговор. Длинная фраза меняет: гость сам перешёл на другой язык.
    """
    свой = language_of(text)
    прошлые = [язык for язык in (language_of(t) for t in earlier) if язык]
    if свой == "en" and прошлые and len((text or "").split()) <= 3:
        return прошлые[0]
    if свой:
        return свой
    if прошлые:
        return прошлые[0]
    return "ru" if _digits(phone).startswith("7") else "en"


def in_language(texts: dict[str, str], language: str, **values: object) -> str:
    """Текст на языке гостя; если перевода нет — по-русски."""
    return render(texts.get(language) or texts["ru"], **values)


