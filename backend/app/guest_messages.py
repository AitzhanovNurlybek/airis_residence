"""
Сообщения гостю по ходу брони. Это файл, который правит отель.

Здесь лежат тексты, которые уходят гостю сами, без участия менеджера:
подтверждение брони, напоминание накануне заезда, просьба об отзыве после
выезда, отклик на отмену.

────────────────────────────────────────────────────────────────────────
КАК ПРАВИТЬ

Меняйте текст в кавычках. Всё, что в фигурных скобках, — подстановка:

    {name}     имя гостя            {number}   номер брони
    {check_in} дата заезда          {check_out} дата выезда
    {nights}   сколько ночей        {room}     категория, уже в скобках
    {phone}    телефон стойки       {check_in_time} время заезда

Скобки удалять нельзя: без них подстановка не сработает и гость увидит
текст как есть. Лишние подстановки не страшны — если поля нет, вместо него
подставится пустая строка, а не ошибка.

────────────────────────────────────────────────────────────────────────
ПОЧЕМУ ТЕКСТЫ ИМЕННО ТАКИЕ

**Одно сообщение на событие.** Соблазн написать три раза «ждём вас» велик,
но WhatsApp считает такие повторы спамом и блокирует номер — отель это уже
проходил. Одно сообщение на событие, и всё.

**Каждое несёт пользу, а не вежливость.** «Спасибо за бронь» без цифр —
шум. «Спасибо, номер такой-то, заезд с 14:00, завтрак включён» — гость
перестаёт держать это в голове и не звонит уточнять.

**Вопрос в конце — только там, где ответ нужен нам.** Накануне заезда
уместно спросить про трансфер: гость всё равно решает, как добираться, и
отель на этом зарабатывает. После выезда — просьба об отзыве. А в
подтверждении брони вопроса нет: гость только что всё решил, дёргать его
нечем.

**Ночь различает два вида сообщений.** Подтверждение брони и отклик на
отмену уходят сразу, в любое время: гость только что сам это сделал и ждёт
ответа именно сейчас. А напоминание накануне заезда и просьба об отзыве
ждут дня — их время выбираем мы, и будить ими человека незачем.

Сам консьерж отвечает на вопросы круглосуточно, без ограничений.
"""

from __future__ import annotations

#: Бронь создана — уходит сразу после уведомления от Exely.
#: Задача: снять с гостя необходимость помнить детали и звонить их уточнять.
BOOKING_CREATED = (
    "{name}, спасибо за бронирование!\n\n"
    "Бронь {number}{room}, заезд {check_in}, выезд {check_out}.\n"
    "Заезд с {check_in_time}, завтрак включён в стоимость.\n\n"
    "Если планы поменяются — напишите сюда или позвоните: {phone}."
)

#: Накануне заезда — уходит утром за день до даты заезда.
#: Единственное сообщение, где мы что-то предлагаем: трансфер отель
#: организует сам, и спросить о нём заранее полезно обоим.
BEFORE_ARRIVAL = (
    "{name}, завтра ждём вас в Airis Residence.\n\n"
    "Бронь {number}, заезд с {check_in_time}, стойка работает круглосуточно — "
    "приезжайте в удобное время.\n\n"
    "Нужен трансфер из аэропорта или помощь с парковкой? Напишите, организуем."
)

#: После выезда — уходит на следующий день.
#: Отзывы гостей прямо влияют на позиции отеля в агрегаторах, а просить их
#: лично на стойке неловко обеим сторонам.
AFTER_DEPARTURE = (
    "{name}, спасибо, что выбрали Airis Residence!\n\n"
    "Если всё понравилось — будем благодарны за короткий отзыв, он помогает "
    "нам больше, чем кажется.\n"
    "А если что-то было не так, напишите прямо сюда: разберёмся."
)

#: Бронь отменена. Не уговариваем и не выпытываем причину: гость уже решил.
#: Одна фраза, что дверь открыта, — этого достаточно.
BOOKING_CANCELLED = (
    "{name}, бронь {number} отменена.\n\n"
    "Если передумаете или понадобятся другие даты — напишите, подберём номер."
)


#: Ответ на голосовое сообщение.
#:
#: Расшифровывать речь консьерж пока не умеет — для этого нужна отдельная
#: служба распознавания. Но молчать нельзя: гость, отправивший голосовое и
#: не получивший ничего, решит, что отель его не читает.
#:
#: Просим текстом и сразу говорим, что можно спросить, — иначе гость просто
#: перескажет голосовое голосовым.
VOICE_NOT_SUPPORTED = (
    "Извините, голосовые пока не распознаю — напишите, пожалуйста, текстом.\n\n"
    "Могу подсказать свободные номера и цены на ваши даты, рассказать про "
    "отель или найти вашу бронь.\n\n"
    "Если удобнее голосом — позвоните на стойку: {phone}, там ответят круглосуточно."
)


#: Какие типы событий Exely к какому сообщению относятся.
#: Слова берутся из уведомления, регистр не важен. Список открытый: чего
#: здесь нет, то просто не вызывает сообщения — молчание безопаснее
#: случайного текста не по адресу.
EVENT_MESSAGES: dict[str, str] = {
    # Так называет события сам Exely (приставку «webpms:» разбор снимает).
    # Проверено на живом уведомлении 2026-08-31.
    "create_booking": BOOKING_CREATED,
    "cancel_booking": BOOKING_CANCELLED,
    "modify_booking": "",
    "bookingcreated": BOOKING_CREATED,
    "reservationcreated": BOOKING_CREATED,
    "created": BOOKING_CREATED,
    "bookingcancelled": BOOKING_CANCELLED,
    "bookingcanceled": BOOKING_CANCELLED,
    "reservationcancelled": BOOKING_CANCELLED,
    "cancelled": BOOKING_CANCELLED,
    "canceled": BOOKING_CANCELLED,
}


def render(template: str, **values: object) -> str:
    """Подставить значения в шаблон.

    Отсутствующее поле превращается в пустую строку, а не в ошибку: тексты
    правит отель, и опечатка в названии подстановки не должна оставлять
    гостя без сообщения вовсе. Двойные пробелы и пустые строки, которые
    появятся на месте пропуска, убираются.
    """

    class _Blank(dict):
        def __missing__(self, key: str) -> str:  # noqa: D105
            return ""

    text = template.format_map(_Blank(values))
    # Пустая подстановка оставляет двойной пробел и висячую запятую —
    # «Бронь X, , заезд». Гость такое замечает.
    text = text.replace(" ,", ",").replace(", ,", ",")
    # Подстановка пустого имени оставляет «, спасибо» — подчищаем.
    lines = [" ".join(line.split()) for line in text.split("\n")]
    while lines and not lines[0]:
        lines.pop(0)
    return "\n".join(lines).replace(" ,", ",").strip()
