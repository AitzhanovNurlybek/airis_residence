#: Буквы, которых нет в русском, — по ним казахский отличается от русского.
KAZAKH_LETTERS = frozenset("әғқңөұүһіӘҒҚҢӨҰҮҺІ")

#: Телефон стойки для текстов, которые уходят, когда справка не загрузилась.
