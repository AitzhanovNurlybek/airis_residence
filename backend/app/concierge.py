def build_system_prompt(
    brief: str,
    today: str,
    *,
    availability: str = "none",
    can_book: bool = False,
    can_find: bool = False,
) -> str:
    """Собрать системный промпт под ровно те возможности, что есть сейчас.

    `can_book` — не настройка, а факт: умеет ли подключённая система писать.
    Раньше правила зависели только от источника наличия, а инструменты — от
    наличия метода create_booking, и в режиме `exely` эти две ветки
    расходились: консьержу перечисляли четыре инструмента бронирования, а
    давали один check_availability. Модель в такой ситуации не сдаётся — она
    отвечает так, будто инструмент отработал. Теперь признак один на оба
    решения, и разойтись им негде.
    """
    rules = RULES
    if availability in ("exely", "stub"):
        rules += LIVE_AVAILABILITY_RULES
        if can_book:
            # Своя шахматка: и пишет, и ищет — правила поиска уже внутри.
            rules += BOOKING_RULES
        else:
            rules += HANDOFF_RULES
            rules += LOOKUP_RULES if can_find else NO_LOOKUP_RULES
    if availability == "stub":
        rules += STUB_AVAILABILITY_RULES

    return (
        f"{rules}\n\n"
        f"Сегодня {today} (время Алматы).\n\n"
        f"=== СПРАВКА ОБ ОТЕЛЕ (единственный источник фактов) ===\n{brief}"
    )


# ─────────────────────────── исполнение инструментов ───────────────────────────


def _parse_date(value: Any) -> date:
    return date.fromisoformat(str(value or "").strip())


def _room_price(facts: dict[str, Any], slug: str, guests: int = 1) -> tuple[str, int] | None:
    """
    Название и цена за ночь для нужного числа гостей.

    Система бронирования отеля считает от числа гостей, а не от номера: в
    Comfort Plus один гость стоит 50 000, а двое — 52 500. Одна цена на номер
    недобирала бы 2 500 за каждую ночь двухместного заезда.
    """
    for room in facts.get("rooms", []):
        if room.get("slug") != slug:
            continue
        single = int(room.get("price") or 0)
        double = int(room.get("priceDouble") or single)
        return room.get("name", slug), (double if guests >= 2 else single)
    return None


#: Слова статуса, которые мы уверенно понимаем. Всё остальное пересказывать
#: своими словами нельзя — см. _status_word.
STATUS_ACTIVE = {"booked", "confirmed", "ok", "active", "checkedin", "checked_in", "guaranteed"}
STATUS_CANCELLED = {"cancelled", "canceled", "declined", "rejected", "noshow", "no_show"}
STATUS_PENDING = {"new", "pending", "onrequest", "on_request", "unconfirmed", "hold"}


def _status_word(status: str) -> str:
    """Статус брони словами, понятными гостю.

    Раньше здесь стояло `"действует" if status == "booked" else "отменена"`.
    Для локальной шахматки это верно — там статус буквально `booked`. Но
    настоящий Exely присылает `Confirmed`, `New`, `CheckedIn`, и любое из них
    превращалось в «отменена»: гостю с подтверждённой бронью сообщали, что
    брони нет. Ошибка, которая стоит гостя, и заметить её можно только на
    стойке.

    Незнакомое слово не переводим и не угадываем: отдаём как есть с пометкой,
    чтобы консьерж сказал «статус такой-то» и предложил уточнить у стойки.
    """
    key = str(status or "").strip().casefold().replace(" ", "").replace("-", "_")
    if key in STATUS_ACTIVE:
        return "действует"
    if key in STATUS_CANCELLED:
        return "отменена"
    if key in STATUS_PENDING:
        return "ждёт подтверждения"
    return f"статус «{status}» (значение неизвестно, не пересказывай своими словами)"


def _describe(booking: Any, *, room: str = "") -> str:
    tail = f", {room}" if room else ""
    return (
        f"{booking.external_id}: {booking.check_in} — {booking.check_out}{tail}, "
        f"{booking.guest_name or 'без имени'}, {booking.total_amount} тенге, "
        f"{_status_word(booking.status)}"
    )


def _tool_room_page(facts: dict[str, Any], args: dict[str, Any]) -> str:
    """Адрес страницы номера — из справки, не из догадки модели."""
    slug = str(args.get("room") or "").strip()
    for room in facts.get("rooms", []):
        if str(room.get("slug")) == slug:
            url = room.get("url")
            if not url:
                break
            return (
                f"Страница номера «{room.get('name')}»: {url}\n"
                f"Там фотографии, {room.get('area')}, {room.get('beds')}."
            )
    codes = ", ".join(sorted(str(r.get("slug")) for r in facts.get("rooms", [])))
    return f"Категории «{slug}» нет. Известные: {codes}"


def _tool_link(settings: Any, facts: dict[str, Any], args: dict[str, Any]) -> str:
    """Собрать ссылку на форму брони.

    Адрес берём из справки (`hotel.url`), а не из настроек: settings.site_url
    на локальной машине указывает на 127.0.0.1, и такую ссылку гостю слать
    некуда. Настройки — запасной вариант, если справка почему-то без адреса.
    """
    slug = str(args.get("room") or "").strip()
    known = {str(room.get("slug", "")) for room in facts.get("rooms", [])}
    if slug and slug not in known:
        codes = ", ".join(sorted(c for c in known if c))
        return f"Категории «{slug}» нет. Известные: {codes}"

    site = str(facts.get("hotel", {}).get("url") or getattr(settings, "site_url", "") or "")
    if not site:
        return "Адрес сайта неизвестен — ссылку собрать не из чего, дай гостю телефон стойки"

    try:
        guests = int(args.get("guests") or 0)
    except (TypeError, ValueError):
        guests = 0

    url = booking_form_url(
        site,
        room_slug=slug,
        check_in=args.get("check_in"),
        check_out=args.get("check_out"),
        guests=guests,
    )
    # Напоминание идёт вместе со ссылкой, а не только в правилах: правила
    # модель читает один раз в начале, а ответ инструмента видит прямо перед
    # тем, как писать гостю.
    return (
        f"Ссылка на форму брони: {url}\n"
        "ВАЖНО: форма откроется на нужной категории, но даты в ней будут "
        "сегодняшние — виджет не умеет их подставлять. Обязательно напиши "
        "гостю, какие даты выбрать в форме, иначе он забронирует не тот период."
    )


async def _tool_availability(
    booking: BookingSystem, args: dict[str, Any], facts: dict[str, Any] | None = None
) -> str:
    try:
        check_in = _parse_date(args.get("check_in"))
        check_out = _parse_date(args.get("check_out"))
    except ValueError:
        return "Даты не разобраны. Нужен формат ГГГГ-ММ-ДД."
    if check_out <= check_in:
        return "Дата выезда должна быть позже даты заезда."

    try:
        result = await booking.availability(check_in, check_out)
    except BookingSystemUnavailable as error:
        return f"Система бронирования не ответила: {error}"

    if not result.offers:
        return "Система бронирования не вернула ни одной категории."

    prefix = ""
    if result.source == "stub":
        prefix = "ТЕСТОВЫЕ ДАННЫЕ (локальная шахматка, не настоящее наличие).\n"

    # Что сайт знает про категорию: площадь, кровати, вместимость. Без этого
    # модель, назвав свободный номер, лезет за описанием в справку отдельным
    # ходом — а на категорию, которой в справке нет (Apart продаётся в Exely,
    # но на сайте его нет вовсе), придумывает описание сама.
    known: dict[str, dict[str, Any]] = {
        str(room.get("slug", "")): room for room in (facts or {}).get("rooms", [])
    }

    lines: list[str] = []
    cancellations: set[str] = set()
    per_rate: list[tuple[int, str]] = []
    for offer in result.offers:
        head = f"- {offer.room_name or offer.room_slug} (код {offer.room_slug}): "
        if not offer.rooms_left:
            lines.append(head + "свободных нет")
            continue
        lines.append(head + f"свободно {offer.rooms_left}")

        room = known.get(offer.room_slug)
        if room:
            about = ", ".join(
                str(v) for v in (room.get("area"), room.get("beds")) if v
            )
            cap = room.get("capacity")
            if cap:
                about += f", до {cap} гост." if about else f"до {cap} гост."
            if about:
                lines.append(f"    {about}")
            if room.get("summary"):
                lines.append(f"    {room['summary']}")
        else:
            # Категория продаётся, но сайт про неё молчит. Придумывать за отель
            # нельзя: гость приедет к другому номеру.
            lines.append(
                "    ВНИМАНИЕ: этой категории нет на сайте, описания у тебя нет. "
                "Назвать её и цену можно, придумывать описание — нельзя; "
                "подробности уточнит стойка."
            )

        rack = None
        if facts:
            priced = _room_price(facts, offer.room_slug)
            rack = priced[1] if priced else None
        # Тарифы, если система их отдаёт. Цена на сайте — прайс, а продаётся
        # номер по тарифу, и он бывает заметно дешевле. Гость, услышавший от
        # консьержа прайс, открывает форму и видит другое число.
        for rate in offer.rates:
            if not _sane_price(rate.price, rack):
                # Цена вне разумных границ — в кабинете отеля явно ошиблись.
                # Гостю такое не показываем: он на неё сошлётся.
                logger.warning(
                    "Подозрительная цена %s на %s при прайсе %s — пропускаю",
                    rate.price, offer.room_slug, rack,
                )
                continue
            about = (
                " с завтраком" if rate.breakfast
                else (" без завтрака" if rate.breakfast is False else "")
            )
            was = f", обычно {rate.was}" if rate.was else ""
            # Сумму за весь период считаем здесь. Умножение в уме модель делает
            # верно почти всегда — «почти» тут и есть проблема: ошибку заметят
            # на стойке при заселении.
            total = f" — за {result.nights} ноч. {rate.price * result.nights} тенге"
            lines.append(
                f"    · {rate.name}: {rate.price} тенге за ночь{about}{was}{total}"
            )
            if rate.cancellation:
                cancellations.add(rate.cancellation)
                per_rate.append((len(lines) - 1, rate.cancellation))

    # Условия отмены у отеля почти всегда одни на все тарифы и категории. При
    # шести категориях и трёх тарифах это девять одинаковых абзацев подряд —
    # они вытесняют из внимания модели то, чем номера различаются. Одинаковые
    # схлопываем в строку под списком, разные оставляем на месте.
    if len(cancellations) == 1:
        lines.append(f"Отмена (одинаково для всех тарифов): {cancellations.pop()}")
    elif cancellations:
        for shift, (index, text) in enumerate(per_rate):
            lines.insert(index + 1 + shift, f"      отмена: {text}")

    return (
        f"{prefix}{check_in} — {check_out}, ночей {result.nights}:\n"
        + "\n".join(lines)
    )


async def _tool_create(
    booking: BookingSystem, args: dict[str, Any], facts: dict[str, Any], guest: dict[str, str]
) -> str:
    if not hasattr(booking, "create_booking"):
        return "Эта система бронирования не умеет оформлять брони отсюда."

    try:
        check_in = _parse_date(args.get("check_in"))
        check_out = _parse_date(args.get("check_out"))
    except ValueError:
        return "Даты не разобраны. Нужен формат ГГГГ-ММ-ДД."

    slug = str(args.get("room_slug") or "").strip()
    guests = max(1, int(args.get("guests") or 1))
    priced = _room_price(facts, slug, guests)
    if priced is None:
        codes = ", ".join(r.get("slug", "") for r in facts.get("rooms", []))
        return f"Категории «{slug}» нет. Есть такие: {codes}"

    room_name, price = priced
    rooms_count = max(1, int(args.get("rooms_count") or 1))
    nights = (check_out - check_in).days

    # Сумму считает сервер, а не модель: иначе в базу однажды попадёт цифра из
    # разговора. Считаем по продажному тарифу, если система его отдала, —
    # прайс из справки выше того, по чему гость реально бронирует.
    sold_at = await _live_price(booking, slug, check_in, check_out, rack=price)
    if sold_at:
        price = sold_at
    amount = price * rooms_count * max(nights, 0)

    try:
        created = await booking.create_booking(
            room_slug=slug,
            rooms_count=rooms_count,
            check_in=check_in,
            check_out=check_out,
            guest_name=str(args.get("guest_name") or "").strip(),
            guest_phone=guest.get("phone", ""),
            amount=amount,
            origin="concierge",
            note=str(args.get("note") or "").strip(),
        )
    except Exception as error:  # noqa: BLE001 — текст ошибки уходит модели как есть
        return f"Оформить не удалось: {error}"

    return (
        f"Бронь оформлена. {_describe(created, room=room_name)}. "
        f"Ночей {nights}, гостей в номере {guests}, цена за ночь {price} тенге."
    )


async def _live_price(
    booking: BookingSystem, slug: str, check_in: date, check_out: date,
    rack: int | None = None,
) -> int | None:
    """Самая низкая продажная цена на категорию. None — система молчит."""
    try:
        result = await booking.availability(check_in, check_out)
    except Exception:  # noqa: BLE001 — цена из справки остаётся запасным вариантом
        return None
    offer = next((o for o in result.offers if o.room_slug == slug), None)
    if not offer or not offer.price_per_night:
        return None
    if not _sane_price(offer.price_per_night, rack):
        logger.warning(
            "Не беру цену %s на %s при прайсе %s — считаю по прайсу",
            offer.price_per_night, slug, rack,
        )
        return None
    return offer.price_per_night


async def _tool_find(booking: BookingSystem, args: dict[str, Any], guest: dict[str, str]) -> str:
    if not hasattr(booking, "find_bookings"):
        return "Эта система бронирования не умеет искать брони отсюда."

    phone = guest.get("phone", "")
    if not phone:
        return "Телефон собеседника неизвестен, поэтому найти его брони нельзя. Предложи стойку."

    mine = await booking.find_bookings(phone=phone)
    wanted = str(args.get("ref") or "").strip().upper()

    if wanted:
        # Своя шахматка ищет по телефону и фильтрует найденное: там номер
        # угадать легко (L-0007), и отдавать бронь по одному номеру нельзя.
        by_phone = [b for b in mine if b.external_id == wanted]
        if by_phone:
            return "\n".join(_describe(b) for b in by_phone)

        # Запасной путь — только там, где по телефону искать нечем.
        #
        # У Exely контактов гостя нет вовсе, зато номер брони длинный
        # (20260902-509506-1262476932) и есть только у самого гостя — по
        # нему выдать можно. А в своей шахматке телефон известен, и номера
        # короткие (L-0007): выдай там бронь по одному номеру — и любой
        # желающий переберёт чужие. Проверка это ловит.
        if not getattr(booking, "finds_by_phone", True) and hasattr(booking, "get_booking"):
            try:
                found = await booking.get_booking(wanted)
            except BookingSystemUnavailable as error:
                return f"Система бронирования не ответила: {error}"
            if found is not None:
                return _describe(found)
        return (
            f"Брони с номером {wanted} не нашлось. Проверь, верно ли записан "
            "номер, и предложи стойку."
        )

    # Гость не помнит номер — ищем по фамилии, но только вместе с датой
    # заезда. Фамилия не пароль: в базе отеля один и тот же человек может
    # быть дважды, а однофамильцы встречаются и подавно. Дата заезда — то,
    # что свой гость помнит точно, а чужой не угадает.
    who = str(args.get("name") or "").strip()
    arrival = str(args.get("arrival") or "").strip()
    if who and arrival:
        try:
            wanted_day = _parse_date(arrival)
        except ValueError:
            return "Дата заезда не разобрана. Нужен формат ГГГГ-ММ-ДД."

        from .booking_sync import find_by_name
        from .db import SessionLocal

        async with SessionLocal() as session:
            found = await find_by_name(session, who, limit=20)
        same_day = [b for b in found if b.check_in == wanted_day]
        if not same_day:
            return (
                f"Брони на фамилию «{who}» с заездом {wanted_day} не нашлось. "
                "Уточни у гостя написание фамилии и дату либо предложи стойку."
            )
        return "\n".join(
            f"{b.number}: {b.check_in} — {b.check_out}, {b.room_name or 'номер'}, "
            f"{b.guest_name}, {b.total_amount} тенге, {_status_word(b.status)}"
            for b in same_day
        )

    if who and not arrival:
        return (
            "Одной фамилии мало — однофамильцы бывают. Спроси у гостя дату "
            "заезда и передай её вместе с фамилией."
        )

    if not mine:
        # Важно: это НЕ значит, что броней нет. Это значит, что искать по
        # телефону нечем. Разница принципиальная — гостю с живой бронью
        # нельзя отвечать «у вас броней нет».
        return (
            "Искать по телефону нельзя: система бронирования не отдаёт контакты "
            "гостя. Попроси номер брони — он в подтверждении, которое отель "
            "прислал после бронирования (20260902-509506-1262476932). Если "
            "номер не сохранился, спроси фамилию и дату заезда."
        )
    return "\n".join(_describe(b) for b in mine)


async def _tool_change(booking: BookingSystem, args: dict[str, Any], guest: dict[str, str]) -> str:
    if not hasattr(booking, "change_booking"):
        return "Эта система бронирования не умеет менять брони отсюда."

    ref = str(args.get("ref") or "").strip().upper()
    if not await _belongs_to_guest(booking, ref, guest):
        return f"Брони {ref} у этого гостя нет."

    kwargs: dict[str, Any] = {}
    try:
        if args.get("check_in"):
            kwargs["check_in"] = _parse_date(args["check_in"])
        if args.get("check_out"):
            kwargs["check_out"] = _parse_date(args["check_out"])
    except ValueError:
        return "Даты не разобраны. Нужен формат ГГГГ-ММ-ДД."
    if args.get("rooms_count"):
        kwargs["rooms_count"] = int(args["rooms_count"])

    if not kwargs:
        return "Не сказано, что менять: нужны новые даты или число номеров."

    try:
        changed = await booking.change_booking(ref, **kwargs)
    except Exception as error:  # noqa: BLE001
        return f"Изменить не удалось: {error}"
    return f"Бронь изменена. {_describe(changed)}"


async def _tool_cancel(booking: BookingSystem, args: dict[str, Any], guest: dict[str, str]) -> str:
    if not hasattr(booking, "cancel_booking"):
        return "Эта система бронирования не умеет отменять брони отсюда."

    ref = str(args.get("ref") or "").strip().upper()
    if not await _belongs_to_guest(booking, ref, guest):
        return f"Брони {ref} у этого гостя нет."

    try:
        cancelled = await booking.cancel_booking(ref, str(args.get("reason") or "").strip())
    except Exception as error:  # noqa: BLE001
        return f"Отменить не удалось: {error}"
    return f"Бронь отменена. {_describe(cancelled)}"


async def _belongs_to_guest(booking: BookingSystem, ref: str, guest: dict[str, str]) -> bool:
    """
    Проверка «это твоя бронь» до вызова, а не в тексте правил.

    Правило в промпте — просьба, а не запрет: достаточно уговорить модель, и
    она вызовет отмену для чужого номера. Здесь же чужая бронь просто не
    находится, сколько её ни проси.
    """
    phone = guest.get("phone", "")
    if not phone or not ref:
        return False
    mine = await booking.find_bookings(phone=phone)
    return any(b.external_id == ref for b in mine)


