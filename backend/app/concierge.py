async def answer(
    settings: Settings,
    *,
    message: str,
    history: list[dict[str, Any]] | None = None,
    today: str,
    booking: BookingSystem | None = None,
    guest: dict[str, str] | None = None,
) -> dict[str, Any]:
    """
    Ответ консьержа на одно сообщение.

    `history` — прошлые реплики в формате [{"role": ..., "content": ...}].
    Хранение диалога — забота канала: у WhatsApp и Instagram свои
    идентификаторы собеседника.

    `booking` — система бронирования, если подключена. Без неё консьерж про
    наличие мест не рассуждает вовсе: инструменты не объявляются, и правило
    «наличие подтвердит стойка» остаётся единственным.

    `guest` — кто пишет: {"phone": ..., "name": ...}. Телефон берётся из
    канала, а не из разговора. Именно по нему решается, чьи брони видны:
    сказанному в переписке «это моя бронь L-0007» верить нельзя.
    """
    if not settings.anthropic_api_key:
        return {"text": FALLBACK, "ok": False, "reason": "нет ключа Anthropic"}

    try:
        facts = await load_facts(settings)
    except KnowledgeUnavailable as error:
        return {"text": FALLBACK, "ok": False, "reason": f"нет фактов: {error}"}

    guest = guest or {}
    mode = booking.source if booking else "none"
    # Один признак на промпт и на инструменты: что обещано в правилах, то и
    # лежит в руках. Порядок важен — сначала считаем возможности, потом
    # собираем промпт.
    can_book = booking is not None and hasattr(booking, "create_booking")
    # Уметь искать брони — не то же самое, что уметь их заводить. Настоящий
    # Exely ищет, когда выдан договорной доступ, но не заводит никогда.
    can_find = booking is not None and bool(getattr(booking, "can_find_bookings", False))

    # Страница номера есть у сайта всегда, даже когда система бронирования не
    # подключена вовсе: рассказать про номер и показать фотографии можно и без
    # наличия.
    tools: list[dict[str, Any]] = [ROOM_PAGE_TOOL]
    if booking is not None:
        tools += FULL_TOOLS if can_book else READ_ONLY_TOOLS
        if can_find and not can_book:
            # В FULL_TOOLS поиск уже есть; здесь добавляем его к чтению.
            tools.append(FIND_TOOL)

    system = build_system_prompt(
        render_brief(facts), today, availability=mode,
        can_book=can_book, can_find=can_find,
    )

    depth = max(0, settings.concierge_history_depth)
    messages: list[dict[str, Any]] = [
        *(history or [])[-depth:],
        {"role": "user", "content": message},
    ]

    headers = {
        "x-api-key": settings.anthropic_api_key,
        "anthropic-version": ANTHROPIC_VERSION,
        "content-type": "application/json",
    }

    tool_calls: list[dict[str, Any]] = []
    spent_in = 0
    spent_out = 0
    # Кешируемая часть считается отдельно: у неё другая цена. Запись в кеш
    # дороже обычного ввода, чтение — заметно дешевле. Без этих двух счётчиков
    # учёт врёт: при включённом кешировании input_tokens падает до десятка,
    # и расход выглядит копеечным, хотя за первый запрос платится за весь
    # промпт целиком.
    spent_cache_write = 0
    spent_cache_read = 0

    # Пять кругов: хватает на «посмотреть наличие → оформить → назвать номер».
    # Предел нужен на случай, если модель зациклится на уточнении, — в
    # мессенджере это выглядело бы как молчание, а стоило бы денег.
    for _ in range(5):
        payload: dict[str, Any] = {
            "model": settings.concierge_model,
            "max_tokens": settings.concierge_max_tokens,
            # Системный промпт — справка об отеле плюс правила — почти не
            # меняется внутри разговора и в цикле из пяти кругов на один
            # ответ гостя уходит заново на каждом круге. Без кеширования
            # это оплачивается по полной цене каждый раз. Anthropic кеширует
            # блок, помеченный cache_control: следующий запрос в той же
            # переписке (и следующий круг внутри этого же ответа) платит за
            # него в разы дешевле — если промпт длиннее минимума для модели,
            # а короче он просто игнорирует пометку без ошибки.
            "system": [
                {"type": "text", "text": system, "cache_control": {"type": "ephemeral"}}
            ],
            "messages": messages,
        }
        if tools:
            payload["tools"] = tools

        try:
            async with httpx.AsyncClient(timeout=60.0) as client:
                response = await client.post(ANTHROPIC_URL, json=payload, headers=headers)
                response.raise_for_status()
                data = response.json()
        except Exception as error:  # noqa: BLE001
            return {"text": FALLBACK, "ok": False, "reason": f"модель недоступна: {error}"}

        usage = data.get("usage", {})
        spent_in += usage.get("input_tokens") or 0
        spent_out += usage.get("output_tokens") or 0
        spent_cache_write += usage.get("cache_creation_input_tokens") or 0
        spent_cache_read += usage.get("cache_read_input_tokens") or 0
        content = data.get("content", [])

        if data.get("stop_reason") == "tool_use" and booking is not None:
            results = []
            for block in content:
                if block.get("type") != "tool_use":
                    continue
                name = block.get("name")
                args = block.get("input") or {}
                tool_calls.append({"name": name, "input": args})

                if name == "room_page":
                    output = _tool_room_page(facts, args)
                elif name == "booking_link":
                    output = _tool_link(settings, facts, args)
                elif name == "check_availability":
                    output = await _tool_availability(booking, args, facts)
                elif name == "create_booking":
                    output = await _tool_create(booking, args, facts, guest)
                elif name == "find_booking":
                    output = await _tool_find(booking, args, guest)
                elif name == "change_booking":
                    output = await _tool_change(booking, args, guest)
                elif name == "cancel_booking":
                    output = await _tool_cancel(booking, args, guest)
                else:
                    output = f"Инструмента {name} нет."

                results.append(
                    {"type": "tool_result", "tool_use_id": block.get("id"), "content": output}
                )
            messages.append({"role": "assistant", "content": content})
            messages.append({"role": "user", "content": results})
            continue

        text = "".join(
            block.get("text", "") for block in content if block.get("type") == "text"
        ).strip()

        if not text:
            return {"text": FALLBACK, "ok": False, "reason": "пустой ответ модели"}

        return {
            "text": text,
            "ok": True,
            "availability": mode,
            "toolCalls": tool_calls,
            "messages": messages + [{"role": "assistant", "content": text}],
            "usage": {
                "in": spent_in,
                "out": spent_out,
                "cacheWrite": spent_cache_write,
                "cacheRead": spent_cache_read,
            },
        }

    return {"text": FALLBACK, "ok": False, "reason": "модель не сошлась за пять кругов"}
