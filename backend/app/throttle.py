"""
Тормоз против подбора пароля.

Общий для входа в админку отеля и в корпоративный кабинет: логика одна, а
двух копий, которые со временем разъедутся, быть не должно.

Честно про ограничения. Счётчик живёт в памяти процесса, а на serverless
экземпляров несколько и живут они минутами — значит настойчивый перебор с
одного адреса всё равно просочится, просто медленнее. Это не замена
нормальному лимиту на входе (Vercel WAF, Cloudflare), а дешёвая преграда,
которая ловит скрипт «пройдись по словарю» и ничего не стоит.

Для кабинета это важнее, чем для админки: там одна известная учётка, а тут
много почтовых адресов, и каждый — отдельная цель.
"""

import time

# ключ → отметки времени попыток
_attempts: dict[str, list[float]] = {}

WINDOW_SECONDS = 300

#: Предел для одной учётной записи. Это основная защита: подбирают всегда
#: конкретный аккаунт.
PER_ACCOUNT = 10

#: Предел для одного адреса у кабинета. Намеренно щедрый: корпоративные
#: клиенты сидят за общим офисным NAT, и десятка на всю компанию не хватит —
#: пара опечаток у двух коллег заперла бы всех остальных.
PER_OFFICE_IP = 50


def client_ip(request) -> str:
    """
    Адрес посетителя.

    За обратным прокси (а на Vercel он есть всегда) настоящий адрес приходит
    в X-Forwarded-For; request.client.host там показывал бы адрес самой
    площадки, и тормоз считал бы всех гостей одним человеком.
    """
    forwarded = request.headers.get("x-forwarded-for", "").split(",")[0].strip()
    if forwarded:
        return forwarded
    return request.client.host if request.client else "unknown"


def too_many(key: str, limit: int = PER_ACCOUNT) -> bool:
    """Отмечает попытку и говорит, не пора ли остановить."""
    now = time.time()
    recent = [t for t in _attempts.get(key, []) if now - t < WINDOW_SECONDS]
    if len(recent) >= limit:
        _attempts[key] = recent
        return True
    recent.append(now)
    _attempts[key] = recent
    return False


def reset(key: str) -> None:
    """Успешный вход обнуляет счётчик: человек не должен страдать за опечатки."""
    _attempts.pop(key, None)
