"""
Время отеля.

Сервер на Vercel живёт в UTC, отель — в Алматы, это плюс пять часов. Значит с
полуночи и до пяти утра по местному времени `date.today()` на сервере всё ещё
показывает вчерашний день. Пять часов в сутки система считает не тот день —
ровно те часы, когда стойка работает, а менеджера рядом нет.

Что от этого ломалось на самом деле:

* платёжка, присланная ночью, выглядела датированной завтрашним днём — и
  уходила менеджеру на разбор вместо того, чтобы засчитаться;
* бронь на вчерашнюю дату ночью проходила проверку «дата уже прошла»;
* консьержу сообщалась вчерашняя дата, и «завтра» в разговоре означало
  сегодня.

Тот же разрыв уже чинили на страницах сайта (`frontend/lib/almaty.ts`) — там
он выдавал себя ошибкой гидратации. На сервере он тише и потому опаснее:
ничего не падает, просто пять часов в сутки решения принимаются не по тому
дню.

Правило простое: в бизнес-логике `date.today()` не вызывать. Здесь `today()`.
"""

from __future__ import annotations

from datetime import date, datetime, timedelta, timezone

try:
    from zoneinfo import ZoneInfo

    HOTEL_TZ = ZoneInfo("Asia/Almaty")
except Exception:  # noqa: BLE001 — на голом образе базы часовых поясов может не быть
    # Алматы круглый год UTC+5, перевода часов нет с 2005 года. Постоянное
    # смещение — не костыль, а точное описание этого пояса.
    HOTEL_TZ = timezone(timedelta(hours=5), "Asia/Almaty")


def now() -> datetime:
    """Текущий момент по времени отеля."""
    return datetime.now(HOTEL_TZ)


def today() -> date:
    """Какое сегодня число в Алматы."""
    return now().date()


def to_hotel(moment: datetime) -> datetime:
    """Перевести момент во время отеля. Наивное время считаем за UTC."""
    if moment.tzinfo is None:
        moment = moment.replace(tzinfo=timezone.utc)
    return moment.astimezone(HOTEL_TZ)


def days_until(when: date) -> int:
    """Сколько дней до даты. Ноль — сегодня, отрицательное — прошло."""
    return (when - today()).days
